const fs = require('fs');
const os = require('os');
const path = require('path');

const BRANCH_PREFIX = /^(patch|minor|major)\//;
const ATTRIBUTION = [
  /generated\s+(with|by)\s+\[?(claude|codex)/i,
  /co-authored-by:\s*(claude|codex)/i,
  /claude\.com\/claude-code/i,
  /\u{1F916}/u,
];
const MCP_GAP = /#\s*mcp-gap\b/i;
const HTTP_CLIENT = /(^|[\s;&|(`'"])(curl|wget|invoke-restmethod|invoke-webrequest|irm|iwr)(\.exe)?(?=[\s;&|)`'"]|$)/i;
const AZ_CMDLET = /\b[A-Z][a-z]+-Az[A-Z]\w*/;
const ADO_AZ_GROUPS = new Set(['devops', 'repos', 'pipelines', 'boards', 'artifacts']);
const SERVICES = {
  azure: 'the Azure MCP server (mcp__azure__* or mcp__azure-personal__*)',
  ado: 'the Azure DevOps MCP servers (mcp__ado-highwaysengland__* or mcp__ado-cloudaande__*)',
  github: 'the GitHub MCP server (mcp__github__*)',
};
const HOSTS = [
  [/\bdev\.azure\.com\b|\b[\w-]+\.visualstudio\.com\b/i, 'ado'],
  [/\bmanagement\.azure\.com\b/i, 'azure'],
  [/\bapi\.github\.com\b/i, 'github'],
];

function segments(command) {
  return command.split(/&&|\|\||[;|\n]/).map(tokens).filter(t => t.length);
}

function tokens(segment) {
  return (segment.match(/"[^"]*"|'[^']*'|\S+/g) || []).map(t => t.replace(/^(["'])(.*)\1$/, '$2'));
}

function program(token) {
  return path.basename(token || '').toLowerCase().replace(/\.(exe|cmd)$/, '');
}

function gitCall(words) {
  let i = words.findIndex(w => program(w) === 'git');
  if (i < 0) return null;
  i++;
  while (i < words.length && words[i].startsWith('-')) {
    if (['-C', '-c', '--git-dir', '--work-tree', '--namespace'].includes(words[i])) i++;
    i++;
  }
  if (i >= words.length) return null;
  return { sub: words[i], args: words.slice(i + 1) };
}

function valueAfter(args, flags) {
  for (let i = 0; i < args.length; i++) {
    if (flags.includes(args[i])) return args[i + 1];
    const long = flags.find(f => f.startsWith('--') && args[i].startsWith(f + '='));
    if (long) return args[i].slice(long.length + 1);
  }
  return undefined;
}

function newBranches(git) {
  const { sub, args } = git;
  if (sub === 'checkout') return [valueAfter(args, ['-b', '-B', '--orphan'])];
  if (sub === 'switch') return [valueAfter(args, ['-c', '-C', '--create', '--force-create', '--orphan'])];
  if (sub === 'worktree' && args[0] === 'add') return [valueAfter(args, ['-b', '-B'])];
  if (sub !== 'branch') return [];
  const positional = args.filter(a => !a.startsWith('-'));
  if (args.some(a => ['-m', '-M', '--move', '-c', '-C', '--copy'].includes(a))) return [positional[positional.length - 1]];
  const readOnly = ['-d', '-D', '--delete', '-l', '--list', '-a', '--all', '-r', '--remotes', '--show-current', '-v', '-vv', '--verbose',
    '--contains', '--no-contains', '--merged', '--no-merged', '--points-at', '-u', '--set-upstream-to', '--unset-upstream', '--edit-description'];
  if (args.some(a => readOnly.includes(a) || a.startsWith('--set-upstream-to=') || a.startsWith('--format'))) return [];
  return [positional[0]];
}

function badBranch(name) {
  return typeof name === 'string' && name.length > 0 && !name.includes('$') && !BRANCH_PREFIX.test(name);
}

function branchMessage(name) {
  return `Branch "${name}" is not allowed. Agents may only create branches named patch/<name>, minor/<name> or major/<name>.`;
}

function attributionIn(text) {
  return typeof text === 'string' && ATTRIBUTION.some(pattern => pattern.test(text));
}

const ATTRIBUTION_MESSAGE = 'Remove the AI attribution (for example "Generated with Claude Code" or "Co-Authored-By: Claude"). Content posted to a remote must not say it was generated by Claude or Codex.';

function forcedAgentsAdd(git) {
  if (git.sub !== 'add') return false;
  const forced = git.args.some(a => a === '--force' || /^-[a-zA-Z]*f[a-zA-Z]*$/.test(a));
  if (!forced) return false;
  const broad = git.args.some(a => ['.', '*', ':/', ':/*', '--all'].includes(a) || /^-[a-zA-Z]*A[a-zA-Z]*$/.test(a));
  return broad || git.args.some(a => !a.startsWith('-') && /(^|[\\/])\.agents([\\/]|$)/.test(a));
}

function serviceForCli(words) {
  let i = 0;
  while (i < words.length && (words[i] === '&' || /^[A-Za-z_]\w*=/.test(words[i]))) i++;
  const name = program(words[i]);
  if (name === 'gh') return 'github';
  if (name === 'az') return ADO_AZ_GROUPS.has((words[i + 1] || '').toLowerCase()) ? 'ado' : 'azure';
  return null;
}

function serviceForHost(text) {
  const match = HOSTS.find(([pattern]) => pattern.test(text));
  return match ? match[1] : null;
}

function mcpMessage(service, what) {
  return `${what} is blocked: query ${SERVICES[service]} instead. If the MCP server cannot do this, add "# mcp-gap" to the command and it will be allowed and logged.`;
}

function logGap(input, command) {
  try {
    const file = path.join(os.homedir(), '.claude', 'hooks', 'mcp-gap.log');
    const entry = { time: new Date().toISOString(), cwd: input.cwd, tool: input.tool_name, command };
    fs.appendFileSync(file, JSON.stringify(entry) + '\n');
  } catch (error) {
  }
}

function readMessageFile(git, cwd) {
  const file = valueAfter(git.args, ['-F', '--file']);
  if (!file || file === '-') return '';
  try {
    return fs.readFileSync(path.resolve(cwd || process.cwd(), file), 'utf8');
  } catch (error) {
    return '';
  }
}

function checkShell(input) {
  const command = String((input.tool_input || {}).command || '');
  const parts = segments(command);
  for (const words of parts) {
    const git = gitCall(words);
    if (!git) continue;
    const bad = newBranches(git).find(badBranch);
    if (bad) return branchMessage(bad);
    if (forcedAgentsAdd(git)) return '.agents/ holds task artefacts and must never be committed. Do not force-add it; stage the specific files you changed instead.';
    if (['commit', 'tag', 'notes', 'merge'].includes(git.sub) && (attributionIn(command) || attributionIn(readMessageFile(git, input.cwd)))) {
      return ATTRIBUTION_MESSAGE;
    }
  }
  let service = null;
  let what = '';
  for (const words of parts) {
    service = serviceForCli(words);
    if (service) {
      what = `The ${program(words.find(w => w !== '&' && !/^[A-Za-z_]\w*=/.test(w)))} CLI`;
      break;
    }
  }
  if (!service && AZ_CMDLET.test(command)) {
    service = 'azure';
    what = 'Az PowerShell';
  }
  if (!service && HTTP_CLIENT.test(command)) {
    service = serviceForHost(command);
    what = 'A direct HTTP call to this service';
  }
  if (!service) return null;
  if (MCP_GAP.test(command)) {
    logGap(input, command);
    return null;
  }
  return mcpMessage(service, what);
}

function stringsIn(value, found = []) {
  if (typeof value === 'string') found.push(value);
  else if (value && typeof value === 'object') Object.values(value).forEach(v => stringsIn(v, found));
  return found;
}

function checkMcp(input) {
  const name = input.tool_name;
  const args = input.tool_input || {};
  if (name === 'mcp__github__create_branch' && badBranch(args.branch)) return branchMessage(args.branch);
  if (/^mcp__ado-[\w-]+__repo_create_branch$/.test(name) && badBranch(args.branchName)) return branchMessage(args.branchName);
  if (stringsIn(args).some(attributionIn)) return ATTRIBUTION_MESSAGE;
  return null;
}

function check(input) {
  const name = String(input.tool_name || '');
  if (name === 'Bash' || name === 'PowerShell') return checkShell(input);
  if (name === 'WebFetch') {
    const service = serviceForHost(String((input.tool_input || {}).url || ''));
    return service ? mcpMessage(service, 'Fetching this service over the web') : null;
  }
  if (/^mcp__(github|ado-[\w-]+)__/.test(name)) return checkMcp(input);
  return null;
}

if (require.main === module) {
  let raw = '';
  process.stdin.on('data', d => (raw += d));
  process.stdin.on('end', () => {
    let input;
    try {
      input = JSON.parse(raw);
    } catch (error) {
      process.exit(0);
    }
    const message = check(input);
    if (message) {
      process.stderr.write(message + '\n');
      process.exit(2);
    }
    process.exit(0);
  });
}

module.exports = { check };
